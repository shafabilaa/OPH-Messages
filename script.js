/* =================================
   2. GET HTML ELEMENTS
================================= */

const welcomeSection =
    document.getElementById("welcomeSection");

const messageSection =
    document.getElementById("messageSection");

const nameInput =
    document.getElementById("nameInput");

const searchButton =
    document.getElementById("searchButton");

const errorMessage =
    document.getElementById("errorMessage");

const messageTitle =
    document.getElementById("messageTitle");

const messageContent =
    document.getElementById("messageContent");

const surpriseButton =
    document.getElementById("surpriseButton");

const surpriseMessage =
    document.getElementById("surpriseMessage");

const surpriseContent =
    document.getElementById("surpriseContent");

const backButton =
    document.getElementById("backButton");

const confettiContainer =
    document.getElementById("confettiContainer");


/* =================================
   3. NORMALIZE NAME
================================= */

function normalizeName(name) {

    return name
        .trim()
        .toLowerCase();

}


/* =================================
   4. SEARCH MESSAGE
================================= */

function findMessage() {

    const name = normalizeName(nameInput.value);

    // Clear previous results
    errorMessage.textContent = "";

    messageSection.classList.add("hidden");

    surpriseMessage.classList.add("hidden");

    // Check empty input
    if (name === "") {

        errorMessage.textContent =
            "Oops! You haven't entered your name yet ♡";

        nameInput.focus();

        return;
    }

    // Find the message
    const result = messages[name];

    // If name doesn't exist
    if (!result) {

        errorMessage.textContent =
            "Hmm... we couldn't find your message. Try another name!";

        return;
    }

    // Display personal message
    messageTitle.textContent = result.title;

    messageContent.textContent = result.message;

    surpriseContent.textContent = result.surprise;

    // Change page
    welcomeSection.classList.add("hidden");

    messageSection.classList.remove("hidden");

    // Reset surprise button
    surpriseButton.disabled = false;

    surpriseButton.textContent =
        "There's more... ✨";

    // Scroll to top
    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


/* =================================
   5. SEARCH EVENT
================================= */

searchButton.addEventListener("click", findMessage);


// Allow Enter key to search
nameInput.addEventListener("keydown", function(event) {

    if (event.key === "Enter") {

        findMessage();

    }

});


/* =================================
   6. SURPRISE INTERACTION
================================= */

surpriseButton.addEventListener("click", function() {

    surpriseMessage.classList.remove("hidden");

    surpriseButton.textContent =
        "Surprise unlocked! ♡";

    surpriseButton.disabled = true;

    createConfetti();

});


/* =================================
   7. CONFETTI ANIMATION
================================= */

function createConfetti() {

    const symbols = ["♡", "✦", "✧", "✿"];

    const colors = [
        "#d991a7",
        "#b9a6d5",
        "#e9b8c7",
        "#f2c98b"
    ];

    for (let i = 0; i < 35; i++) {

        const confetti = document.createElement("span");

        confetti.classList.add("confetti");

        confetti.textContent =
            symbols[Math.floor(Math.random() * symbols.length)];

        confetti.style.left =
            Math.random() * 100 + "vw";

        confetti.style.color =
            colors[Math.floor(Math.random() * colors.length)];

        confetti.style.fontSize =
            (Math.random() * 12 + 10) + "px";

        confetti.style.animationDelay =
            Math.random() * 0.8 + "s";

        confettiContainer.appendChild(confetti);

        // Remove after animation
        setTimeout(() => {

            confetti.remove();

        }, 4000);

    }

}


/* =================================
   8. BACK TO WELCOME PAGE
================================= */

backButton.addEventListener("click", function() {

    messageSection.classList.add("hidden");

    welcomeSection.classList.remove("hidden");

    nameInput.value = "";

    errorMessage.textContent = "";

    surpriseMessage.classList.add("hidden");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

    nameInput.focus();

});
